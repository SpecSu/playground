/**
 * Offline exact layouts for all 12 uploaded avatars and 20 fixed-size catches.
 * node --experimental-strip-types scripts/generate-fishing-catch-layouts.mjs
 * node --experimental-strip-types scripts/generate-fishing-catch-layouts.mjs --check
 * Optional: --workers=4 (1–8), --force (ignore resumable item checkpoints).
 * No browser, renderer, network access, or gameplay-time solver is required.
 */
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {existsSync, mkdirSync, readFileSync, renameSync, writeFileSync} from 'node:fs';
import {registerHooks} from 'node:module';
import {fileURLToPath} from 'node:url';
import {isMainThread, parentPort, Worker} from 'node:worker_threads';

// The production avatar rig has extensionless TS imports. Keep this offline
// entry self-contained rather than depending on the test runner's loader.
registerHooks({resolve(specifier, context, nextResolve) {
  if ((specifier.startsWith('./') || specifier.startsWith('../')) && context.parentURL) {
    const url = new URL(specifier, context.parentURL);
    if (!/\.[a-z]+$/i.test(url.pathname) && existsSync(new URL(`${url.href}.ts`))) {
      return nextResolve(`${url.href}.ts`, context);
    }
  }
  return nextResolve(specifier, context);
}});

const ROOT = new URL('../', import.meta.url);
const OUTPUT = new URL('lib/fishing-catch-layouts.generated.ts', ROOT);
const CHECKPOINTS = new URL('.local-qa/v035/precomputed/', ROOT);
const VERSION = 1;
const SOURCE_PATHS = [
  'scripts/generate-fishing-catch-layouts.mjs',
  'package-lock.json',
  'lib/fishing-avatar.ts',
  'lib/fishing-surface-contact.ts',
  'lib/fishing-catch-snapshot.ts',
  'lib/fishing-catch-layout-cache.ts',
  'components/fishing/MarineModels.ts',
  'lib/fishing-catalog.ts',
  'lib/fishing-world.ts',
  'lib/fishing-avatar-props.ts',
  'lib/fishing-avatar-contact-regions.ts',
  'lib/club-avatar-rig.ts',
  'lib/fishing-avatar-catalog.ts',
  'lib/room-types.ts',
];
const {FISHING_AVATAR_CATALOG} = await import('../lib/fishing-avatar-catalog.ts');
const {MARINE_SPECIES} = await import('../lib/fishing-catalog.ts');
const expectedKeys = FISHING_AVATAR_CATALOG.flatMap(({id}) => MARINE_SPECIES.map(species => `${id}/${species.id}`));

const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const fingerprint = () => ({
  sourceHashes: Object.fromEntries(SOURCE_PATHS.map(path => [path, hash(readFileSync(new URL(path, ROOT)))])),
  assetHashes: Object.fromEntries(FISHING_AVATAR_CATALOG.map(({id}) => {
    const path = `public/avatars/cast-v1/${id}.glb`;
    return [path, hash(readFileSync(new URL(path, ROOT)))];
  })),
});
const fingerprintId = value => hash(JSON.stringify(value));
const itemUrl = key => new URL(`${key.replace('/', '--')}.json`, CHECKPOINTS);
function atomicWrite(url, text) {
  const temporary = new URL(`${url.href}.tmp-${process.pid}`);
  writeFileSync(temporary, text);
  renameSync(temporary, url);
}

function validateLayout(key, layout) {
  const species = MARINE_SPECIES.find(item => item.id === key.split('/')[1]);
  assert.ok(species, `Unknown species in ${key}`);
  assert.equal(layout.lengthCm, species.fixedCm, `${key}: stale fixed length`);
  assert.ok(Number.isFinite(layout.scale) && layout.scale > 0, `${key}: invalid scale`);
  for (const property of ['size', 'position', 'rotation', 'approachDirection', 'naturalSize']) {
    assert.ok(Array.isArray(layout[property]) && layout[property].length === 3, `${key}: invalid ${property}`);
    assert.ok(layout[property].every(Number.isFinite), `${key}: non-finite ${property}`);
  }
  for (const property of ['size', 'naturalSize']) assert.ok(layout[property].every(value => value > 0), `${key}: empty ${property}`);
  assert.ok(Number.isInteger(layout.tested) && layout.tested >= 0, `${key}: invalid tested count`);
  assert.ok(Number.isInteger(layout.total) && layout.total >= layout.tested, `${key}: invalid candidate count`);
  assert.ok(!('fixedCm' in layout), `${key}: fixed size must only be stored as lengthCm`);
}

function validateLayouts(layouts) {
  assert.equal(FISHING_AVATAR_CATALOG.length, 12, 'Expected 12 canonical uploaded avatars');
  assert.equal(MARINE_SPECIES.length, 20, 'Expected 20 canonical marine species');
  assert.deepEqual(Object.keys(layouts).sort(), [...expectedKeys].sort(), 'Generated cache must contain exactly the 240 canonical keys');
  for (const key of expectedKeys) validateLayout(key, layouts[key]);
}

function writeGenerated(layouts, hashes) {
  const ordered = Object.fromEntries(expectedKeys.map(key => [key, layouts[key]]));
  atomicWrite(OUTPUT, `// Generated by scripts/generate-fishing-catch-layouts.mjs. Do not edit by hand.\n`
    + `// Exact source geometry; one canonical fixed-size layout per avatar/species.\n`
    + `export const FISHING_CATCH_LAYOUT_VERSION = ${VERSION};\n`
    + `export const FISHING_CATCH_LAYOUT_FINGERPRINT: { sourceHashes: Record<string, string>; assetHashes: Record<string, string> } = ${JSON.stringify(hashes, null, 2)};\n`
    + `export const FISHING_CATCH_LAYOUTS: Record<string, { lengthCm: number; scale: number; size: number[]; position: number[]; rotation: number[]; approachDirection: number[]; naturalSize: number[]; tested: number; total: number }> = ${JSON.stringify(ordered, null, 2)};\n`);
}

async function checkGenerated() {
  // Only imports stored data and catalog IDs. No avatar/mesh construction.
  const generated = await import(`${OUTPUT.href}?check=${Date.now()}`);
  assert.equal(generated.FISHING_CATCH_LAYOUT_VERSION, VERSION, 'Unsupported layout version');
  validateLayouts(generated.FISHING_CATCH_LAYOUTS);
  assert.deepEqual(generated.FISHING_CATCH_LAYOUT_FINGERPRINT, fingerprint(), 'Layout source/asset fingerprint is stale; regenerate the cache');
  console.log(`Verified ${expectedKeys.length} fixed-size layouts and all ${SOURCE_PATHS.length + FISHING_AVATAR_CATALOG.length} source/asset hashes.`);
}

async function solveAvatar({avatarId, speciesIds}) {
  const THREE = await import('three');
  const {GLTFLoader} = await import('three/addons/loaders/GLTFLoader.js');
  const {createFishingAvatar} = await import('../lib/fishing-avatar.ts');
  const {measureFishingCatchBounds} = await import('../lib/fishing-catch-snapshot.ts');
  const {createMarineModel} = await import('../components/fishing/MarineModels.ts');
  const {catchDisplayScale, disposeObject} = await import('../lib/fishing-world.ts');
  const bytes = readFileSync(new URL(`public/avatars/cast-v1/${avatarId}.glb`, ROOT));
  const loader = new GLTFLoader().register(() => ({name: 'offline-texture-placeholder', loadTexture: () => Promise.resolve(new THREE.Texture())}));
  const template = (await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '')).scene;
  const avatar = createFishingAvatar(avatarId, 'precomputed-catch-layout', {template});
  try {
    for (const speciesId of speciesIds) {
      const started = performance.now();
      const species = MARINE_SPECIES.find(item => item.id === speciesId);
      const lengthCm = species.fixedCm, scale = catchDisplayScale(lengthCm);
      const model = createMarineModel(species.id, lengthCm);
      try {
        model.scale.setScalar(scale);
        model.rotation.set(0, 0, 0);
        const naturalSize = measureFishingCatchBounds(model).getSize(new THREE.Vector3()).toArray();
        const size = avatar.prepareCatch(model);
        const position = avatar.positionCatch(new THREE.Vector3(), size);
        const {tested = 0, total = 0} = avatar.root.userData.fishingCatchSolve ?? {};
        const layout = {
          lengthCm, scale, size: size.toArray(), position: position.toArray(),
          rotation: [model.rotation.x, model.rotation.y, model.rotation.z],
          approachDirection: avatar.catchApproachDirection.toArray(), naturalSize, tested, total,
        };
        const key = `${avatarId}/${species.id}`;
        validateLayout(key, layout);
        parentPort.postMessage({type: 'layout', key, layout, elapsedMs: performance.now() - started});
      } finally { disposeObject(model); }
    }
  } finally { avatar.dispose(); }
}

async function generate(args) {
  const workersArgument = args.find(arg => arg.startsWith('--workers='));
  const count = workersArgument ? Number(workersArgument.slice('--workers='.length)) : 4;
  assert.ok(Number.isInteger(count) && count >= 1 && count <= 8, '--workers must be an integer from 1 to 8');
  mkdirSync(CHECKPOINTS, {recursive: true});
  const initialHashes = fingerprint(), checkpointId = fingerprintId(initialHashes);
  const layouts = {}, timings = {};
  if (!args.includes('--force')) for (const key of expectedKeys) {
    try {
      const checkpoint = JSON.parse(readFileSync(itemUrl(key), 'utf8'));
      if (checkpoint.version !== VERSION || checkpoint.fingerprintId !== checkpointId || checkpoint.key !== key) continue;
      validateLayout(key, checkpoint.layout);
      layouts[key] = checkpoint.layout;
      timings[key] = checkpoint.elapsedMs;
    } catch { /* Missing, stale, or incomplete item checkpoints are recomputed. */ }
  }
  const resumed = Object.keys(layouts).length;
  const jobs = FISHING_AVATAR_CATALOG.map(({id}) => ({avatarId: id, speciesIds: MARINE_SPECIES.filter(species => !layouts[`${id}/${species.id}`]).map(species => species.id)})).filter(job => job.speciesIds.length);
  const started = performance.now();
  console.log(`Generating ${expectedKeys.length} layouts with ${Math.min(count, jobs.length)} workers; resumed ${resumed} item checkpoints.`);
  atomicWrite(new URL('generation-start.json', CHECKPOINTS), JSON.stringify({version: VERSION, fingerprintId: checkpointId, fingerprint: initialHashes, startedAt: new Date().toISOString(), resumed}, null, 2));
  if (jobs.length) await new Promise((resolve, reject) => {
    const workers = new Set();
    let completedAvatars = 0, failed = false;
    const totalAvatars = jobs.length;
    const fail = error => {
      if (failed) return;
      failed = true;
      for (const worker of workers) void worker.terminate();
      reject(error);
    };
    const dispatch = worker => {
      if (failed) return;
      const job = jobs.shift();
      if (job) worker.postMessage(job);
      else { workers.delete(worker); void worker.terminate(); }
    };
    for (let index = 0; index < Math.min(count, totalAvatars); index++) {
      const worker = new Worker(new URL(import.meta.url), {execArgv: ['--experimental-strip-types']});
      workers.add(worker);
      worker.on('error', fail);
      worker.on('exit', code => { if (workers.has(worker) && !failed) fail(new Error(`Layout worker exited unexpectedly with code ${code}`)); });
      worker.on('message', message => {
        if (failed) return;
        try {
          if (message.type === 'error') { fail(new Error(message.error)); return; }
          if (message.type === 'layout') {
            validateLayout(message.key, message.layout);
            layouts[message.key] = message.layout;
            timings[message.key] = message.elapsedMs;
            atomicWrite(itemUrl(message.key), JSON.stringify({version: VERSION, fingerprintId: checkpointId, key: message.key, layout: message.layout, elapsedMs: message.elapsedMs}, null, 2));
            const done = Object.keys(layouts).length, computed = done - resumed, elapsed = (performance.now() - started) / 1000;
            console.log(JSON.stringify({done, total: expectedKeys.length, key: message.key, itemSeconds: +(message.elapsedMs / 1000).toFixed(3), elapsedSeconds: +elapsed.toFixed(2), estimatedRemainingSeconds: +((expectedKeys.length - done) * elapsed / Math.max(1, computed)).toFixed(1)}));
          } else if (message.type === 'done') {
            completedAvatars += 1;
            dispatch(worker);
            if (completedAvatars === totalAvatars) resolve();
          }
        } catch (error) { fail(error); }
      });
      dispatch(worker);
    }
  });
  validateLayouts(layouts);
  // Never attest an older result to newer geometry, algorithms, or dependencies.
  // Both source and GLB bytes must stay frozen for the entire generation run.
  const finalHashes = fingerprint(), finalId = fingerprintId(finalHashes);
  const changedSources = SOURCE_PATHS.filter(path => initialHashes.sourceHashes[path] !== finalHashes.sourceHashes[path]);
  const changedAssets = Object.keys(initialHashes.assetHashes).filter(path => initialHashes.assetHashes[path] !== finalHashes.assetHashes[path]);
  if (changedSources.length || changedAssets.length) {
    // A worker may have loaded changed bytes before they were noticed. Mark
    // every result from this run unusable even if those files are later reverted.
    for (const key of expectedKeys) atomicWrite(itemUrl(key), JSON.stringify({version: VERSION, fingerprintId: `invalidated:${checkpointId}`, key, layout: layouts[key], elapsedMs: timings[key]}, null, 2));
    const rejected = {rejectedAt: new Date().toISOString(), changedSources, changedAssets, initialFingerprint: initialHashes, finalFingerprint: finalHashes};
    atomicWrite(new URL('generation-rejected.json', CHECKPOINTS), JSON.stringify(rejected, null, 2));
    throw new Error(`Sources/assets changed during generation; generated output was not replaced. Freeze and rerun: ${[...changedSources, ...changedAssets].join(', ')}`);
  }
  for (const key of expectedKeys) atomicWrite(itemUrl(key), JSON.stringify({version: VERSION, fingerprintId: finalId, key, layout: layouts[key], elapsedMs: timings[key]}, null, 2));
  writeGenerated(layouts, finalHashes);
  const summary = {
    version: VERSION, count: expectedKeys.length, resumed, completedAt: new Date().toISOString(), elapsedSeconds: (performance.now() - started) / 1000,
    fingerprintsVerifiedUnchanged: true,
    fingerprint: finalHashes, timings,
  };
  atomicWrite(new URL('generation-summary.json', CHECKPOINTS), JSON.stringify(summary, null, 2));
  console.log(`Wrote ${expectedKeys.length} layouts to ${fileURLToPath(OUTPUT)} in ${summary.elapsedSeconds.toFixed(2)} seconds.`);
  await checkGenerated();
}

if (!isMainThread) {
  parentPort.on('message', async job => {
    try { await solveAvatar(job); parentPort.postMessage({type: 'done', avatarId: job.avatarId}); }
    catch (error) { parentPort.postMessage({type: 'error', error: error?.stack ?? String(error)}); }
  });
} else {
  const args = process.argv.slice(2);
  const invalid = args.filter(arg => !['--check', '--force', '--help'].includes(arg) && !arg.startsWith('--workers='));
  assert.equal(invalid.length, 0, `Unknown arguments: ${invalid.join(', ')}`);
  if (args.includes('--help')) console.log('Usage: node --experimental-strip-types scripts/generate-fishing-catch-layouts.mjs [--check] [--workers=4] [--force]');
  else if (args.includes('--check')) await checkGenerated();
  else await generate(args);
}
