test('four-species V15 eggs retain their saved outcomes and growth, including a pre-growth egg',()=>{
 // Literal outcomes captured before the fifth species was introduced, not regenerated by the current picker.
 const eggs:FarmEgg[]=[
  {id:'egg-1',source:'shop',species:'pig',sex:'male',size:'large',growth:{version:1,scales:[.9264974592486396,1.4130382214792334,1.7227537420811132]},location:'bag',boughtAt:at},
  {id:'egg-2',source:'shop',species:'cow',sex:'male',size:'normal',growth:{version:1,scales:[.6897417454158994,1.001920394346004,1.2714847440831365]},location:'bag',boughtAt:at},
  {id:'egg-4',source:'shop',species:'bunny',sex:'male',size:'normal',growth:{version:1,scales:[.7736471805106917,1.0134358934879621,1.1772580400109292]},location:'bag',boughtAt:at},
  {id:'egg-9',source:'shop',species:'sheep',sex:'female',size:'normal',location:'bag',boughtAt:at},
 ];
 const s=ready(9);s.eggs=structuredClone(eggs);s.collection=['sheep','pig','cow','bunny'];
 const storage=memory();storage.setItem(model.LEGACY_MINIMAL_STORAGE_KEY,legacyRaw(s));storage.setItem('dreamina-minimal-farm-v1','untouched');
 let restored=model.loadMinimalState(storage,at+86_400_000);
 assert.deepEqual(restored.eggs,eggs);
 assert.deepEqual(restored.collection,s.collection);
 assert.equal(restored.version,3);
 assert.equal(model.saveMinimalState(storage,restored),true);
 restored=model.loadMinimalState(storage,at+86_400_000);
 assert.deepEqual(restored.eggs,eggs);
 assert.equal(storage.getItem('dreamina-minimal-farm-v1'),'untouched');
 // The old bunny roll now falls in a different five-species interval; hatching must still use saved bunny.
 const old=eggs[2];restored=command(restored,{type:'placeEgg',eggId:old.id,at:{x:1,z:1}}).state;
 const hatch=command(restored,{type:'hatch',eggId:old.id},restored.updatedAt+10_000);
 assert.equal(hatch.accepted,true);
 assert.deepEqual(identity(hatch.state.animals[0]),identity(old));
});

test('pre-growth four-species animals preserve original identities, scales and 60-second adulthood',()=>{
 const s=ready();s.animals=expectedSpecies.slice(0,4).map((species,i)=>{
  const a=duck(`legacy-${i}`,i%2?'female':'male',{x:1+i%2,z:2+Math.floor(i/2)});
  a.species=species as Species;a.name=`saved-${species}`;a.size=i===1?'large':i===2?'giant':'normal';a.bornAt=at-60_000;
  delete a.growth;delete a.growthAgeMs;return a;
 });
 const original=s.animals.map(identity),scales=s.animals.map(a=>model.animalScale(a,at));
 const storage=memory();storage.setItem(model.LEGACY_MINIMAL_STORAGE_KEY,legacyRaw(s));
 const loaded=model.loadMinimalState(storage,at);
 assert.deepEqual(loaded.animals.map(identity),original);
 assert.deepEqual(loaded.animals.map(a=>model.animalScale(a,at)),scales);
 assert.ok(loaded.animals.every(a=>model.isAdult(a,at)&&a.growth===undefined));
 assert.equal(model.saveMinimalState(storage,loaded),true);
});

