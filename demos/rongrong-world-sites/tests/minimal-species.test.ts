test('save validation rejects unknown species in animals, eggs and collection without overwriting good data',()=>{
 const valid=ready();valid.eggs=[duckEgg()];valid.animals=[duck()];valid.collection=['duck'];const storage=memory();
 assert.equal(model.saveMinimalState(storage,valid),true);const original=storage.getItem(model.MINIMAL_STORAGE_KEY);
 for(const invalid of ['wolf','Duck','__proto__','constructor','toString',null,{},['duck']])for(const target of ['animal','egg','collection']){
  const bad=structuredClone(valid);
  if(target==='animal')(bad.animals[0] as unknown as {species:unknown}).species=invalid;
  else if(target==='egg')(bad.eggs[0] as unknown as {species:unknown}).species=invalid;
  else (bad.collection as unknown[])[0]=invalid;
  assert.equal(model.saveMinimalState(storage,bad),false,`${target} rejects ${JSON.stringify(invalid)}`);
  assert.equal(storage.getItem(model.MINIMAL_STORAGE_KEY),original);
  assert.equal(model.loadMinimalState({getItem:()=>JSON.stringify(bad),setItem:()=>{}},at).welcomeClaimed,false);
 }
});

