import * as model from '../src/minimal/model.ts';
import type {AnimalGrowthProfile,AnimalSize,FarmEgg,MinimalAnimal,MinimalState,Species} from '../src/minimal/model.ts';

const at=1_793_000_000_000;
const expectedSpecies=['sheep','pig','cow','bunny','duck'];
const growth:AnimalGrowthProfile={version:1,scales:[.7,1,1.2]};
const command=(s:MinimalState,c:Parameters<typeof model.minimalCommand>[1],now=s.updatedAt)=>model.minimalCommand(s,c,now);
function ready(sequence=0){const s=command(model.createMinimalState(at),{type:'welcome'}).state;s.player={x:1,z:1};s.sequence=sequence;return s;}
function memory(){const data=new Map<string,string>();return {getItem:(key:string)=>data.get(key)??null,setItem:(key:string,value:string)=>{data.set(key,value);}};}
function legacyRaw(s:MinimalState){const old=JSON.parse(JSON.stringify(s));old.version=2;for(const field of ['biomeLayoutVersion','exploredBiomes','biomeCompatibilityGrants','biomeCompatibilityReason'])delete old[field];for(const t of old.tiles){delete t.naturalTerrain;if(t.terrain==='desert'||t.terrain==='glacier')t.terrain=model.terrainFor(t);}return JSON.stringify(old);}
function duck(id='duck-a',sex:'male'|'female'='male',position={x:2,z:2}):MinimalAnimal{return {id,name:'小鸭',species:'duck',sex,size:'normal',growth:structuredClone(growth),growthAgeMs:120_000,position,activity:'idle',energy:80,bond:0,bornAt:at-120_000,activityUntil:at+99_000};}
function duckEgg(size:AnimalSize='normal'):FarmEgg{return {id:'saved-duck-egg',source:'shop',species:'duck',sex:'female',size,growth:structuredClone(growth),location:'bag',boughtAt:at};}
const identity=(a:Pick<MinimalAnimal,'species'|'sex'|'size'|'growth'>)=>({species:a.species,sex:a.sex,size:a.size,growth:a.growth});

test('default grassland eggs sample its three species uniformly without changing sex or rarity coverage',()=>{
 const counts=new Map<string,number>(),sexes=new Set(),sizes=new Set();
 for(let sequence=0;sequence<5000;sequence++){
  const result=command(ready(sequence),{type:'buyEgg'});
  assert.equal(result.accepted,true);
  assert.equal(result.state.coins,90);
  const egg=result.state.eggs[0];counts.set(egg.species,(counts.get(egg.species)??0)+1);sexes.add(egg.sex);sizes.add(egg.size);
 }
 assert.deepEqual([...counts.keys()].sort(),['cow','pig','sheep']);
 for(const [species,count] of counts)assert.ok(count>=1500&&count<=1833,`${species}: ${count}/5000 is near one third`);
 assert.deepEqual([...sexes].sort(),['female','male']);
 assert.deepEqual([...sizes].sort(),['giant','large','normal']);
});

